import { readFile } from "node:fs/promises";
import path from "node:path";
import { randomBytes } from "node:crypto";
import JSZip from "jszip";
import { NextRequest } from "next/server";
import { pool } from "@/lib/db";

export const dynamic = "force-dynamic";

// Ships the browser extension as a zip, with config.js rewritten to bake in
// this archive's address + save token — extract, load unpacked, done. The
// source lives in <app root>/extension (copied into the image by the
// Dockerfile; process.cwd() is web/ in dev and /app in the container).

const FILES = [
  "manifest.json",
  "background.js",
  "options.html",
  "options.js",
  "README.md",
  "icons/icon16.png",
  "icons/icon48.png",
  "icons/icon128.png",
];

async function saveToken(): Promise<string> {
  const existing = await pool.query("select value from app_settings where key = 'SAVE_TOKEN'");
  if (existing.rows[0]?.value) return existing.rows[0].value;
  await pool.query(
    "insert into app_settings (key, value) values ('SAVE_TOKEN', $1) on conflict (key) do nothing",
    [randomBytes(16).toString("hex")],
  );
  const { rows } = await pool.query("select value from app_settings where key = 'SAVE_TOKEN'");
  return rows[0].value;
}

export async function GET(req: NextRequest) {
  let origin: string;
  try {
    const parsed = new URL(req.nextUrl.searchParams.get("origin") ?? "");
    if (!["http:", "https:"].includes(parsed.protocol)) throw new Error("bad scheme");
    origin = parsed.origin;
  } catch {
    return new Response("origin query param must be a valid http(s) URL", { status: 400 });
  }

  try {
    const token = await saveToken();
    const dir = path.join(process.cwd(), "extension");
    const zip = new JSZip();
    for (const f of FILES) {
      zip.file(`xbkmrk-extension/${f}`, await readFile(path.join(dir, f)));
    }
    zip.file(
      "xbkmrk-extension/config.js",
      `// Generated by the archive's Settings page — pre-configured for this install.\n` +
        `// Values saved in the extension's options page take precedence.\n` +
        `const BAKED = ${JSON.stringify({ origin, token })};\n`,
    );
    const buf = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
    return new Response(new Uint8Array(buf), {
      headers: {
        "content-type": "application/zip",
        "content-disposition": 'attachment; filename="xbkmrk-extension.zip"',
      },
    });
  } catch (err) {
    console.error("extension download failed:", err);
    return new Response((err as Error).message, { status: 500 });
  }
}
